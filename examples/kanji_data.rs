//! Builds data/kanji.tsv from KANJIDIC2 (https://www.edrdg.org/kanjidic/kanjidic2.xml.gz).
//! Run with `cargo run --example kanji_data -- path/to/kanjidic2.xml`.
//! Keeps the 2,136 Jōyō kanji (grades 1–6, and 8 for secondary school),
//! sorted by grade, then by newspaper frequency within a grade.

use std::env;
use std::fmt::Write as _;
use std::fs;

const HEADER: &str = "\
# The 2,136 Jōyō kanji, in school grade order (8 = secondary school).
# kanji\tgrade\ton readings\tkun readings\tmeanings (French, else English)
# From KANJIDIC2 by the Electronic Dictionary Research and Development Group,
# https://www.edrdg.org/edrdg/licence.html, CC BY-SA 4.0. Generated by examples/kanji_data.rs.
";

struct Entry {
    kanji: String,
    grade: u8,
    freq: u32,
    on: Vec<String>,
    kun: Vec<String>,
    meanings: Vec<String>,
    english: bool, // no French meaning in KANJIDIC2
}

/// "つめ.たい" → "つめ(たい)": the part after the dot is okurigana.
fn kun(reading: &str) -> String {
    match reading.split_once('.') {
        Some((stem, okurigana)) => format!("{stem}({okurigana})"),
        None => reading.to_string(),
    }
}

fn main() {
    let path = env::args().nth(1).expect("chemin de kanjidic2.xml");
    let xml = fs::read_to_string(path).unwrap();
    let options = roxmltree::ParsingOptions {
        allow_dtd: true,
        ..Default::default()
    };
    let doc = roxmltree::Document::parse_with_options(&xml, options).unwrap();

    let mut entries = Vec::new();
    for character in doc.descendants().filter(|n| n.has_tag_name("character")) {
        let text = |tag: &str| {
            character
                .descendants()
                .find(|n| n.has_tag_name(tag))
                .and_then(|n| n.text())
        };
        let Some(grade) = text("grade").and_then(|g| g.parse::<u8>().ok()) else {
            continue;
        };
        if grade > 8 {
            continue; // 9 and 10 are name-only kanji (jinmeiyō)
        }
        let readings = |kind: &str| -> Vec<String> {
            character
                .descendants()
                .filter(|n| n.has_tag_name("reading") && n.attribute("r_type") == Some(kind))
                .filter_map(|n| n.text().map(str::to_string))
                .collect()
        };
        let meanings = |lang: Option<&str>| -> Vec<String> {
            character
                .descendants()
                .filter(|n| n.has_tag_name("meaning") && n.attribute("m_lang") == lang)
                .filter_map(|n| n.text().map(str::to_string))
                .collect()
        };
        // "radical un (no. 1)" is noise for a learner, unless it's the only meaning.
        let without_radicals = |m: Vec<String>| -> Vec<String> {
            let kept: Vec<String> = m
                .iter()
                .filter(|s| !s.starts_with("radical"))
                .cloned()
                .collect();
            if kept.is_empty() { m } else { kept }
        };
        let french = without_radicals(meanings(Some("fr")));
        let english = french.is_empty();
        entries.push(Entry {
            kanji: text("literal").unwrap().to_string(),
            grade,
            freq: text("freq")
                .and_then(|f| f.parse().ok())
                .unwrap_or(u32::MAX),
            on: readings("ja_on"),
            kun: readings("ja_kun").iter().map(|r| kun(r)).collect(),
            meanings: if english {
                without_radicals(meanings(None))
            } else {
                french
            },
            english,
        });
    }
    entries.sort_by_key(|e| (e.grade, e.freq));

    let mut out = String::from(HEADER);
    for e in &entries {
        let fields = [&e.on, &e.kun, &e.meanings];
        assert!(
            fields
                .iter()
                .flat_map(|f| f.iter())
                .all(|s| !s.contains(['|', '\t'])),
            "{}",
            e.kanji
        );
        let [on, kun, meanings] = fields.map(|f| f.join("|"));
        writeln!(out, "{}\t{}\t{on}\t{kun}\t{meanings}", e.kanji, e.grade).unwrap();
    }
    fs::create_dir_all("data").unwrap();
    fs::write("data/kanji.tsv", out).unwrap();

    let english: Vec<&str> = entries
        .iter()
        .filter(|e| e.english)
        .map(|e| e.kanji.as_str())
        .collect();
    println!("{} kanji écrits dans data/kanji.tsv", entries.len());
    println!(
        "Sans sens français ({}) : {}",
        english.len(),
        english.join(" ")
    );
}
